// Seeds one Supabase Auth account per ProcureWise role plus the matching procurewise.users profile.
// Idempotent: existing accounts get their password reset and their role re-applied.
// Usage: pnpm seed:demo   (needs VITE_SUPABASE_URL + SUPABASE_SERVICE_ROLE_KEY in .env)
import "dotenv/config";
import { createClient } from "@supabase/supabase-js";
import { randomBytes } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import pg from "pg";

const ACCOUNTS = [
  { email: "admin@procurewise.demo", name: "Demo Admin", role: "admin" },
  { email: "approver@procurewise.demo", name: "Demo Administrative Approver", role: "administrative_approver" },
  { email: "officer@procurewise.demo", name: "Demo Procurement Officer", role: "procurement_officer" },
  { email: "enduser@procurewise.demo", name: "Demo End-User", role: "end_user" },
];

const url = process.env.VITE_SUPABASE_URL;
const serviceKey = process.env.SUPABASE_SERVICE_ROLE_KEY;
if (!url || !serviceKey) throw new Error("VITE_SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY are required in .env.");

const envPath = path.resolve(".env");
let password = process.env.SEED_DEMO_PASSWORD;
if (!password) {
  password = `Pw-${randomBytes(9).toString("base64url")}-9`;
  const env = fs.existsSync(envPath) ? fs.readFileSync(envPath, "utf8") : "";
  fs.appendFileSync(envPath, `${env && !env.endsWith("\n") ? "\n" : ""}SEED_DEMO_PASSWORD=${password}\n`);
  console.log("Generated SEED_DEMO_PASSWORD and saved it to .env (gitignored).");
}

const supabase = createClient(url, serviceKey, { auth: { autoRefreshToken: false, persistSession: false } });

async function ensureAuthUser({ email, name }) {
  const attributes = { password, email_confirm: true, user_metadata: { full_name: name } };
  const created = await supabase.auth.admin.createUser({ email, ...attributes });
  if (!created.error) return { id: created.data.user.id, status: "created" };
  if (created.error.code !== "email_exists") throw new Error(`${email}: ${created.error.message}`);
  // listUsers can't filter by email; generateLink returns the existing user without sending mail.
  const link = await supabase.auth.admin.generateLink({ type: "magiclink", email });
  if (link.error) throw new Error(`${email}: ${link.error.message}`);
  const updated = await supabase.auth.admin.updateUserById(link.data.user.id, attributes);
  if (updated.error) throw new Error(`${email}: ${updated.error.message}`);
  return { id: link.data.user.id, status: "updated" };
}

const results = [];
for (const account of ACCOUNTS) results.push({ ...account, ...(await ensureAuthUser(account)) });

const sqlString = (value) => `'${String(value).replaceAll("'", "''")}'`;
const profileSql = `-- Generated by scripts/seed-demo-accounts.mjs. Safe to re-run.
insert into procurewise.users ("openId", name, email, "loginMethod", role)
values
${results.map((r) => `  (${sqlString(r.id)}, ${sqlString(r.name)}, ${sqlString(r.email)}, 'supabase', ${sqlString(r.role)})`).join(",\n")}
on conflict ("openId") do update
  set name = excluded.name, email = excluded.email, role = excluded.role, "updatedAt" = now();
`;

const connectionString = process.env.SUPABASE_DATABASE_URL || process.env.DATABASE_URL;
let profilesApplied = false;
if (connectionString) {
  const client = new pg.Client({ connectionString, ssl: { rejectUnauthorized: false } });
  await client.connect();
  try {
    await client.query("SET search_path TO procurewise, public");
    await client.query(profileSql);
    profilesApplied = true;
  } finally {
    await client.end();
  }
} else {
  const sqlPath = path.resolve("scripts/seed-demo-profiles.sql");
  fs.writeFileSync(sqlPath, profileSql);
  console.log(`\nNo SUPABASE_DATABASE_URL configured, so role profiles were NOT written.\nRun ${path.relative(".", sqlPath)} in the Supabase SQL Editor to assign roles.`);
}

console.log("\nAuth accounts:");
console.table(results.map(({ email, role, status }) => ({ email, role, auth: status, profile: profilesApplied ? "applied" : "pending SQL" })));
console.log(`Password for all accounts: ${password}`);
